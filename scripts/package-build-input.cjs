const fs = require('node:fs');
const path = require('node:path');
const {sync} = require('glob');
const AdmZip = require('adm-zip');
const root = path.resolve(__dirname,'..');
const pkg = require('../package.json');
const ignore = pkg.build.files.filter(p=>p.startsWith('!')).map(p=>p.slice(1));
ignore.push('**/data/**','**/.env*');
const files = new Set();
files.add('scripts/java-launch-regression.test.cjs');
files.add('scripts/launch-log-fixes.test.cjs');
files.add('scripts/launcher-maintenance.test.cjs');
files.add('scripts/optional-renderer.test.cjs');
files.add('scripts/viewer-activity.test.cjs');
files.add('scripts/apply-viewer-activity.cjs');
files.add('scripts/verify-player-profiles.cjs');
files.add('scripts/PlayerProfileSmoke.java');
files.add('scripts/verify-java-runtimes.cjs');
for(const pattern of pkg.build.files.filter(p=>!p.startsWith('!')))for(const file of sync(pattern,{cwd:root,nodir:true,ignore}))files.add(file);
for(const file of ['package-lock.json','afterPack.js','bat-client.ico','build/icon.png','bat-client-agent/build/libs/bat-cosmetics.jar','test/platform.test.cjs','scripts/smoke-packaged.cjs','scripts/build-portable.js','.github/workflows/platform-packages.yml'])files.add(file);
const zip = new AdmZip();
for(const file of files)zip.addLocalFile(path.join(root,file),path.posix.dirname(file.replace(/\\/g,'/'))==='.'?'':path.posix.dirname(file.replace(/\\/g,'/')));
fs.mkdirSync(path.join(root,'build'),{recursive:true});
zip.writeZip(path.join(root,'build/platform-build-input.zip'));
console.log('BUILD_INPUT_OK '+files.size+' files');
